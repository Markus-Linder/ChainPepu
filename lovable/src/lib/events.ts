export function todayKey(date = new Date()): string {
  return date.toISOString().slice(0, 10);
}

/** The theme of a given day. Same index in every language, so one chain reads naturally everywhere. */
export function themeForDay(day: string, lang: Lang = "en"): string {
  const [y, m, d] = day.split("-").map(Number);
  const list = THEMES[lang] ?? THEMES.en;
  return list[(y * 372 + m * 31 + d) % list.length];
}

export function secondsUntilMidnightUtc(now = new Date()): number {
  const next = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate() + 1));
  return Math.max(0, Math.floor((next.getTime() - now.getTime()) / 1000));
}

/** Title to show for a chain: daily chains are translated, everything else is shown as written. */
export function displayTitle(c: { title: string; daily_day?: string | null }, lang: Lang): string {
  return c.daily_day ? themeForDay(c.daily_day, lang) : c.title;
}

export function secondsUntil(iso: string, now = new Date()): number {
  return Math.max(0, Math.floor((new Date(iso).getTime() - now.getTime()) / 1000));
}
